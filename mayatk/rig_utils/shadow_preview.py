"""A live Viewport 2.0 preview of a horizon rig: the artist drags the light
and sees the outline morph, exactly as Unity and the WebXR viewer will show it.

Both DCC rig types show the same silhouette texture in the viewport -- the
horizon map rides in the emission slot at weight 0 as a data carrier that only
the engines interpret. This module is R7 (*the DCC shows the artist something
true*) for the horizon type: a hardware shader on the plane that evaluates the
map per fragment from the live source, contact and ground.

The evaluation is not written here. It is ``pythontk/geo_utils/shadow_horizon.glsl``
-- the one text every engine and both DCCs run -- assembled at run time through
:meth:`pythontk.ShadowHorizon.shader_source` behind a Maya host prologue: the
uniform block, the ``.ogsfx`` / ``.fx`` scaffolding, and ``SH_Fetch``, the
texel hook that owns Maya's texture-row convention. Maya is a Python process
when it needs the shader, so it carries no mirror.

**Display state, never rig content.** The preview swaps only the plane's
shading-group *membership*: the real ``standardSurface`` network stays intact
and connected, so every accessor that walks it (the silhouette's file node,
the opacity chain, the rebuild's shader sniff) keeps resolving through the
stored snapshot. Nothing about it is exported -- the ``"shadow"`` export
preparer detaches every preview before an FBX is written and republishes the
metadata afterwards -- and a scene reopened with a preview on rebinds the
effect from the file beside the horizon PNG.

**Two devices, one body.** Viewport 2.0 runs DirectX 11 or OpenGL Core Profile
per the user's preference (``MAYA_VP2_DEVICE_OVERRIDE`` per process). A
``dx11Shader`` node compiles the ``.fx`` spelling, a ``GLSLShader`` node the
``.ogsfx``; their uniforms bind identically, so the Python is shared and only
the language, the node type and the file extension differ. Legacy OpenGL
(Pixel Shader 4) cannot compile the effect and is refused with the message
that says so. Both bind the map promoted to 16 bits (``TEXTURE_SUFFIX``): the
OpenGL path sRGB-decodes any 8-bit texture a ``GLSLShader`` samples, whatever
the file node says, and a 16-bit texture has no sRGB format to decode.
"""

from __future__ import annotations

import json
import os
import re
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

try:
    import maya.cmds as cmds
except ImportError as error:
    print(__file__, error)
import pythontk as ptk

from mayatk.core_utils._core_utils import CoreUtils
from mayatk.env_utils._env_utils import EnvUtils
from mayatk.mat_utils._mat_utils import MatUtils

__all__ = ["ShadowPreview"]


# The host prologues. ``{body}`` takes ``ShadowHorizon.shader_source(language)``
# verbatim; everything else is Maya's: semantics, annotations, the texel hook.
#
# SH_Fetch's row convention, MEASURED (shadow_preview_device_check.py, both
# devices): a texel fetch at row 0 reads the PNG's TOP row -- Maya's loader
# does not flip the image for texelFetch / Load the way its UV convention
# (V = 0 at the bottom) might suggest. So a tile's row 0 (the PNG's top row,
# the frame's b0 edge) maps straight through, with no flip; the bottom-up
# branch stays so the next measurement can refute this one in a single line.
# Unity's Load, by contrast, needs the flip.

_OGSFX = """#version 410
// GENERATED by mayatk.rig_utils.shadow_preview -- rewritten on every attach
// from pythontk/geo_utils/shadow_horizon.glsl. Not a source file: edit that.

uniform mat4 gWVPXf : WorldViewProjection < string UIWidget = "None"; >;
uniform mat4 gWorldXf : World < string UIWidget = "None"; >;

// The contact frame in WORLD space, and the source -- driven live by DG nodes.
uniform vec3 gOrigin < string UIName = "Contact Origin (world)"; > = {{0.0, 0.0, 0.0}};
uniform vec3 gAxisA < string UIName = "Frame A (world)"; > = {{1.0, 0.0, 0.0}};
uniform vec3 gAxisB < string UIName = "Frame B (world)"; > = {{0.0, 0.0, 1.0}};
uniform vec3 gAxisUp < string UIName = "Frame Up (world)"; > = {{0.0, 1.0, 0.0}};
uniform vec3 gSource < string UIName = "Source (world)"; > = {{0.0, 5.0, 0.0}};
uniform float gSourceW < string UIName = "Source: 1 = position, 0 = shine direction"; > = 1.0;
uniform float gSourceDiameter < string UIName = "Source Diameter"; > = 0.0;
uniform float gSourceAngle < string UIName = "Source Angle (rad)"; > = 0.0;
uniform float gGround < string UIName = "Ground (frame height)"; > = 0.0;
// The map's layout -- set once per plane from the record's horizon block.
// Annotated like every other tweakable: the plugins expose an unannotated
// uniform as an attribute, but whether its VALUE reaches the shader is
// what shadow_preview_device_check.py measures per device.
uniform float gSize < string UIName = "Footprint Pixels"; > = 128.0;
uniform float gSpans < string UIName = "Spans per Column"; > = 2.0;
uniform float gLevels < string UIName = "Pyramid Levels"; > = 7.0;
uniform float gBoundsA0 < string UIName = "Footprint a0"; > = -1.0;
uniform float gBoundsA1 < string UIName = "Footprint a1"; > = 1.0;
uniform float gBoundsB0 < string UIName = "Footprint b0"; > = -1.0;
uniform float gBoundsB1 < string UIName = "Footprint b1"; > = 1.0;
uniform float gHeightScale < string UIName = "Height Scale"; > = 1.0;
uniform float gRectSX < string UIName = "Rect Scale X"; > = 1.0;
uniform float gRectSY < string UIName = "Rect Scale Y"; > = 1.0;
uniform float gRectOX < string UIName = "Rect Offset X"; > = 0.0;
uniform float gRectOY < string UIName = "Rect Offset Y"; > = 0.0;
uniform float gOpacity < string UIName = "Opacity"; > = 1.0;
uniform float gIntensity < string UIName = "Intensity"; > = 1.0;

// Bound to the map's 16-bit promotion (TEXTURE_SUFFIX), never the 8-bit map:
// on this path VP2 sRGB-decodes any 8-bit texture -- Raw colour space, colour
// management and MayaGammaCorrection change nothing (measured) -- and a
// 16-bit texture has no sRGB format to decode.
uniform texture2D gHorizonTex <
    string ResourceName = "";
    string UIName = "Horizon Map";
    string ResourceType = "2D";
    string UIWidget = "FilePicker";
>;
// Explicit, mip-free sampler state, and NOT optional: OpenGL's default
// minification filter is mipmapped, and a texture VP2 uploads without mips is
// then INCOMPLETE -- it samples as zeros and textureSize reports 0 x 0
// (measured: the floating layer vanished, then the whole map). NEAREST also
// says what the shader means: the map is data and is never filtered.
uniform sampler2D gHorizonSamp = sampler_state {{
    Texture = <gHorizonTex>;
    TEXTURE_MIN_FILTER = NEAREST;
    TEXTURE_MAG_FILTER = NEAREST;
    TEXTURE_WRAP_S = CLAMP_TO_EDGE;
    TEXTURE_WRAP_T = CLAMP_TO_EDGE;
}};

attribute vs_input {{
    vec3 in_position : POSITION;
}}

attribute vs_to_ps {{
    vec3 ps_world;
}}

attribute ps_output {{
    vec4 colourOut : COLOR0;
}}

GLSLShader VS
{{
    void main()
    {{
        ps_world = (gWorldXf * vec4(in_position, 1.0)).xyz;
        gl_Position = gWVPXf * vec4(in_position, 1.0);
    }}
}}

GLSLShader PS
{{
#define SH_ROWS_FROM_BOTTOM {rows_from_bottom}

// The shared body's texel hook: the map's tiles sit side by side, each S
// texels square, row 0 of a tile the PNG's top row (the frame's b0 edge),
// while the texture's row 0 is whichever edge Maya's loader put there.
vec4 SH_Fetch(int tile, int xi, int yi)
{{
    ivec2 size = textureSize(gHorizonSamp, 0);
    int S = int(gSize + 0.5);
    int px = int(gRectOX * float(size.x) + 0.5) + tile * S + xi;
#if SH_ROWS_FROM_BOTTOM
    int py = int(gRectOY * float(size.y) + 0.5) + (S - 1 - yi);
#else
    int py = int((1.0 - gRectOY - gRectSY) * float(size.y) + 0.5) + yi;
#endif
    return texelFetch(gHorizonSamp, ivec2(px, py), 0);
}}

{body}
    void main()
    {{
        ShField g = ShMakeField(
            int(gSize + 0.5), int(gSpans + 0.5), int(gLevels + 0.5),
            vec4(gBoundsA0, gBoundsA1, gBoundsB0, gBoundsB1), gHeightScale, gGround);
        float a = ShAlpha(g, ps_world, gOrigin, gAxisA, gAxisB, gAxisUp,
                          vec4(gSource, gSourceW), vec2(gSourceDiameter, gSourceAngle));
        colourOut = vec4(0.0, 0.0, 0.0, a * gOpacity * gIntensity);
    }}
}}

technique Main
<
    string Transparency = "Transparent";
>
{{
    pass p0
    {{
        VertexShader (in vs_input, out vs_to_ps) = VS;
        PixelShader (in vs_to_ps, out ps_output) = PS;
    }}
}}
"""

